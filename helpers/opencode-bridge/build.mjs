// Build the bridge into the package data the controller ships (ADR 0007 D2.2).
//
//   node build.mjs           write src/autoforge/sdk_helpers/opencode_bridge.mjs and its
//                            sha256 into the manifest's opencode-sdk entry
//   node build.mjs --check   fail when the committed bundle, or the manifest's sha256,
//                            differs from a fresh build
//
// The bundle is one self-contained ES module with the SDK client inlined. Its
// first lines carry the SDK's license notice. esbuild's output depends only
// on its version, the sources and these options, all pinned here and in
// package-lock.json, so a rebuild from the same lock reproduces it byte for
// byte; the manifest's sha256 is the digest of that file (tests check both).
import { build } from "esbuild"
import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const here = (path) => fileURLToPath(new URL(path, import.meta.url))
const OUTPUT = here("../../src/autoforge/sdk_helpers/opencode_bridge.mjs")
const MANIFEST = here("../../src/autoforge/sdk_helpers/manifest.json")
// The opencode-sdk entry's sha256 line, as the manifest is laid out.
const PIN = /("file": "opencode_bridge\.mjs",\n\s*"sha256": )("[0-9a-f]{64}"|null)/
const sdk = JSON.parse(await readFile(here("node_modules/@opencode-ai/sdk/package.json"), "utf8"))
const license = (await readFile(here("SDK-LICENSE"), "utf8")).trimEnd()

const banner = [
  "// AutoForge's OpenCode SDK bridge: generated by helpers/opencode-bridge/build.mjs.",
  "// Do not edit: change helpers/opencode-bridge/src/ and rebuild (docs/development.md).",
  `// It inlines @opencode-ai/sdk ${sdk.version} (${sdk.license}), whose license follows:`,
  "//",
  ...license.split("\n").map((line) => (line ? `// ${line}` : "//")),
  "",
].join("\n")

const result = await build({
  entryPoints: [here("src/bridge.mjs")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  write: false,
  minify: false,
  sourcemap: false,
  legalComments: "none",
  charset: "utf8",
  logLevel: "warning",
  define: { __SDK_VERSION__: JSON.stringify(sdk.version) },
  banner: { js: banner },
})
const bundle = result.outputFiles[0].contents
const digest = createHash("sha256").update(bundle).digest("hex")
const manifest = await readFile(MANIFEST, "utf8")
const pinned = PIN.exec(manifest)
if (!pinned) {
  console.error(`${MANIFEST} has no opencode-sdk sha256 line this script knows`)
  process.exit(1)
}

if (process.argv.includes("--check")) {
  const committed = await readFile(OUTPUT).catch(() => Buffer.alloc(0))
  if (!Buffer.from(bundle).equals(committed)) {
    console.error(`${OUTPUT} differs from a fresh build: run \`npm run build\` and commit it`)
    process.exit(1)
  }
  if (pinned[2] !== `"${digest}"`) {
    console.error(`the manifest's opencode-sdk sha256 is not the bundle's: run \`npm run build\``)
    process.exit(1)
  }
  console.log(`the committed bundle matches a fresh build (sha256 ${digest})`)
} else {
  await writeFile(OUTPUT, bundle)
  await writeFile(MANIFEST, manifest.replace(PIN, `$1"${digest}"`))
  console.log(`wrote ${OUTPUT} (sha256 ${digest}) and its manifest entry`)
}
