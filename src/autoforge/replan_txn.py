"""The REPLAN_REEXECUTE transaction: typed durable state and pure verifiers.

REPLAN_REEXECUTE is the only phase in which the controller performs a
*destructive* GitHub write on work an agent produced: it closes the PR that
holds the accumulated review findings and activates a replacement in its
place. Nothing about that write is recoverable by re-running it, so the phase
is modelled as one explicit transaction rather than as a sequence of
independent checks.

Everything here is pure. GitHub I/O and state persistence live in the engine;
this module owns the *decisions*, so the normal path and the crash-recovery
path cannot drift apart by construction — they call the same predicates on
the same persisted intent.

Lifecycle (monotonic; ``REJECTED`` is terminal)::

    PENDING ──► PREPARED ──► VERIFIED ──► SUPERSEDE_INTENT ──► SUPERSEDED ──► (activated)
        │           │             │                │                │
        │           │             │                ▼                │
        │           │             │          COMPENSATING           │
        │           │             │                │                │
        └───────────┴─────────────┴────────────────┴────────────────┴──► REJECTED

``COMPENSATING`` is entered when the close landed on facts that had already
moved; it is persisted *before* the reopen, so a crash after a successful
reopen resumes into "finish undoing", never into "close again".

``SUPERSEDE_INTENT`` is written *before* ``gh pr close``, together with the
source PR's ``closed`` issue-event count. Issue events are append-only, so a
resume that finds the source still OPEN can prove from that count whether any
close landed after the intent: none did, and the close is retried once
(:func:`verify_close_never_ran`); one did, and the reopen that followed is a
human decision the controller never overrides.

``PREPARED`` is written *before* the agent is invoked, and carries the
transaction id. Because that id cannot exist anywhere before it is persisted,
"crashed before invoking the agent" and "crashed while the agent ran" are the
same recoverable state: either a PR carrying the id exists, or none does.

Causal provenance
-----------------
A replacement belongs to a transaction only if its PR body carries the
controller-generated marker for *that* transaction id:

.. code-block:: text

    <!-- autoforge-replan-transaction: {"transaction_id": "...", ...} -->

The id is random, generated by the controller, persisted before invocation,
handed to the agent as prompt data, and read back from GitHub. Shape alone
("an open PR linked to the issue", "the only other PR") is never proof:
:func:`select_bound_candidate` ignores every unmarked PR and every PR that
already existed when the transaction was prepared. The marker is also
re-checked on the last read before the destructive write
(:func:`verify_target_marker`), because a body can be edited after the
controller verified it.

The same marker carries the agent's *attestation* — how many historical
findings it accounted for, and whether its own tests passed. Putting the
attestation on GitHub rather than only in the CONTROL_RESULT is what lets
recovery enforce exactly the same acceptance rules as the normal path: after
a crash there is no CONTROL_RESULT to consult, but the marker is still there.
"""

